#!/usr/bin/env python3
"""Generate ``ur_description/urdf/grasp_attach.urdf.xacro`` from the objects in a world file.

For every pickable object a Gazebo ``DetachableJoint`` plugin is added to the robot.  It does
nothing until a message arrives on its attach topic; then it welds the object to
``wrist_3_link`` (the gripper is lumped into it by the URDF->SDF converter) *keeping the
current relative pose*, and detaches again on the detach topic.  This is the "virtual grasp"
that makes pick-and-place reliable once the fingers are closed around the object.

Usage:  ros2 run bin_picking_ai gen_attach_xacro <world.sdf> <out.xacro>
(re-run it whenever you add or rename a pickable object in the world)
"""
import re
import sys

SKIP_MODELS = {'Desk', 'FoodCourtTable1', 'TrashBin'}


def parse_world(path):
    s = open(path, encoding='utf-8').read()
    objs = []
    for m in re.finditer(r"<include>\s*<uri>([^<]+)</uri>\s*<name>(\w+)</name>", s):
        uri, name = m.groups()
        model = uri.rstrip('/').split('/')[-1]
        if model in SKIP_MODELS:
            continue
        objs.append((name, model))
    return objs


def model_link(world_path, model):
    import os
    d = os.path.join(os.path.dirname(world_path), '..', 'models', model, 'model.sdf')
    sdf = open(d, encoding='utf-8').read()
    return re.search(r"<link name=['\"](\w+)['\"]", sdf).group(1)


def main(argv=None):
    argv = argv or sys.argv[1:]
    if len(argv) != 2:
        print(__doc__)
        return 1
    world, out = argv
    lines = ['<?xml version="1.0"?>',
             '<!-- AUTO-GENERATED by bin_picking_ai/tools/gen_attach_xacro.py - do not edit by hand. -->',
             '<robot xmlns:xacro="http://wiki.ros.org/xacro">',
             '  <xacro:macro name="grasp_attach_plugins" params="parent_link">']
    for name, model in parse_world(world):
        link = model_link(world, model)
        lines += [
            '    <gazebo>',
            '      <plugin filename="gz-sim-detachable-joint-system"',
            '              name="gz::sim::systems::DetachableJoint">',
            '        <parent_link>${parent_link}</parent_link>',
            f'        <child_model>{name}</child_model>',
            f'        <child_link>{link}</child_link>',
            f'        <attach_topic>/bin_picking/attach/{name}</attach_topic>',
            f'        <detach_topic>/bin_picking/detach/{name}</detach_topic>',
            f'        <output_topic>/bin_picking/attach_state/{name}</output_topic>',
            '        <suppress_child_warning>true</suppress_child_warning>',
            '      </plugin>',
            '    </gazebo>']
    lines += ['  </xacro:macro>', '</robot>', '']
    open(out, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'wrote {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
